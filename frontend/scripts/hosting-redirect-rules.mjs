export function buildRedirectsFile(indexablePaths) {
  const seoLines = [...new Set(
    (indexablePaths || [])
      .map((p) => String(p || '/').replace(/\/$/, '') || '/')
      .filter((p) => p !== '/')
  )]
    .sort()
    .map((p) => `${p}  ${p}/index.html  200`);

  const lines = [
    '# Generated by frontend/scripts/hosting-redirect-rules.mjs — do not hand-edit.',
    '# Canonical apex',
    'http://youtubeboosterai.com/*  https://youtubeboosterai.com/:splat  301!',
    'http://www.youtubeboosterai.com/*  https://youtubeboosterai.com/:splat  301!',
    'https://www.youtubeboosterai.com/*  https://youtubeboosterai.com/:splat  301!',
    '',
    '# Retired URLs Google already crawled',
    ...LEGACY_301.map(([from, to]) => `${from}  ${to}  301`),
    '/audit-topics/*  /audit/:splat  301',
    '',
    '# Unique static HTML for indexable routes (before any SPA fallback)',
    ...seoLines,
    '',
    '# App shell — private SPA routes only',
    ...SPA_200_LINES
  ];
  return `${lines.join('\n')}\n`;
}
